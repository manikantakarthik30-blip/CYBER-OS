import 'dart:convert';
import '../../data/models/scan_result.dart';
import '../../data/models/security_report.dart';

class ReportGenerator {
  static SecurityReport generateReport(ScanResult scanResult) {
    final buffer = StringBuffer();

    buffer.writeln('====================================================');
    buffer.writeln('          CYBER_OS SECURITY AUDIT REPORT            ');
    buffer.writeln('====================================================');
    buffer.writeln('PROJECT: ${scanResult.projectName}');
    buffer.writeln('TARGET: ${scanResult.targetUrlOrPath}');
    buffer.writeln('AUDIT TIMESTAMP: ${scanResult.scannedAt.toUtc().toIso8601String()}');
    buffer.writeln('STATUS: ${scanResult.securityScore >= 70 ? "PASS" : "FAIL"}');
    buffer.writeln('SECURITY SCORE: ${scanResult.securityScore}/100');
    buffer.writeln('DEPLOY VERDICT: ${scanResult.deployStatus == "SAFE_TO_DEPLOY" ? "SAFE TO DEPLOY" : "NOT SAFE TO DEPLOY"}');
    buffer.writeln('----------------------------------------------------');
    buffer.writeln('MODULE STATUS BREAKDOWN:');
    buffer.writeln('  [${scanResult.secretsDetected ? "FAIL" : "PASS"}] Secret Detection Engine');
    buffer.writeln('  [${scanResult.mcpSecure ? "PASS" : "FAIL"}] MCP Security Protocol');
    buffer.writeln('  [${scanResult.dependenciesSafe ? "PASS" : "FAIL"}] Dependency CVE Check');
    buffer.writeln('  [${scanResult.apiSecure ? "PASS" : "FAIL"}] API Surface & Encryption');
    buffer.writeln('  [${scanResult.promptInjectionSafe ? "PASS" : "FAIL"}] AI Prompt Firewall');
    buffer.writeln('----------------------------------------------------');
    buffer.writeln('VULNERABILITIES IDENTIFIED (${scanResult.vulnerabilities.length}):');

    if (scanResult.vulnerabilities.isEmpty) {
      buffer.writeln('  ✓ Zero security vulnerabilities detected.');
    } else {
      for (int i = 0; i < scanResult.vulnerabilities.length; i++) {
        final v = scanResult.vulnerabilities[i];
        buffer.writeln('${i + 1}. [${v.severity}] ${v.title}');
        buffer.writeln('   Location: ${v.location}');
        buffer.writeln('   Category: ${v.category ?? "General"}');
        buffer.writeln('   Details:  ${v.description}');
        buffer.writeln('   Fix:      ${v.fix}');
        if (v.codeSnippet != null && v.codeSnippet!.isNotEmpty) {
          buffer.writeln('   Snippet:  ${v.codeSnippet}');
        }
        buffer.writeln('');
      }
    }

    buffer.writeln('====================================================');
    buffer.writeln('Generated by CYBER_OS Kernel v1.0');

    final markdown = buffer.toString();
    return SecurityReport(
      title: 'Security Audit — ${scanResult.projectName}',
      scanResult: scanResult,
      summaryMarkdown: markdown,
    );
  }

  static String exportAsJson(ScanResult scanResult) {
    const encoder = JsonEncoder.withIndent('  ');
    return encoder.convert(scanResult.toJson());
  }
}
